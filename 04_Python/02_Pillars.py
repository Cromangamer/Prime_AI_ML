# we have 4 pillars of OOP in python
# 1. Encapsulation
# 2. Abstraction
# 3. Inheritance
# 4. Polymorphism

# 1. Encapsulation 
    # Wrapping data and methods into a Singel class is called Encapsulation.

    # we can give three types of access modifiers in python
    # 1. Public: can be accessed from anywhere
    # 2. Protected: can be accessed within the class and its subclasses
    # 3. Private: can be accessed only within the class

# 3. Inheritance
    # Inheritance is a mechanism in which one class acquires the property of another class.

    # we can give three types of inheritance in python
    # 1. Single Inheritance: A class inherits from one superclass.
    # 2. Multiple Inheritance: A class inherits from multiple superclasses.
    # 3. Multilevel Inheritance: A class inherits from a superclass, which in turn inherits from another superclass.

