# Arithmetic Operators
a = 10
b = 5
c = a + b  # Addition
d = a - b  # Subtraction
e = a * b  # Multiplication
f = a / b  # Division
g = a % b  # Modulus
h = a ** b  # Exponentiation


#  Comparison Operators
x = 10
y = 5
z = x > y   # Greater than
w = x < y   # Less than
v = x == y  # Equal to
u = x != y  # Not equal to
t = x <= y  # Less than or equal to
s = x >= y  # Greater than or equal to

# Logical Operators
p = True
q = False
r = p and q  # Logical AND
o = p or q   # Logical OR
n = not p    # Logical NOT

# Assignment Operators
m = 10
m += 5  # Addition assignment
m -= 3  # Subtraction assignment
m *= 2  # Multiplication assignment
m /= 4  # Division assignment
m %= 3  # Modulus assignment
m **= 2  # Exponentiation assignment
